<h2>Eligibility for Integrated Law via CUET (Programme Code 121)</h2>

<p>Per Chapter 2 of the brochure:</p>

<ul>
<li>Pass in <strong>Class 12 (10+2)</strong> of CBSE or equivalent with a minimum of <strong>50% marks in aggregate</strong>* and must also have passed <strong>English (core / elective / functional)</strong> as a subject.</li>
<li>* "Aggregate of 50% marks in the 12th class for the purpose of eligibility will be taken as the aggregate of the <strong>best four subjects</strong> (unless otherwise specified) including English."</li>
<li>Reserved categories (SC/ST/OBC/PwD): standard 5% relaxation per university policy.</li>
<li>Marks are <strong>not rounded off</strong> &mdash; 49.99% will not become 50% (Important Instruction #28).</li>
</ul>

<p style="font-size:13px;background:#fee2e2;padding:12px 16px;border-left:4px solid #dc2626;border-radius:4px;color:#7f1d1d">
<strong>BCI Bar (Critical):</strong> Per Chapter 2 of the brochure quoting BCI Letter <strong>BCI:D:1823/2010 (LE) dated 31.11.2010</strong>: <em>"The applicants who have obtained 10+2 or graduation/post graduation through Open Universities system directly without having any basic qualification for prosecuting such students are not eligible for admission in the law courses."</em> If your Class 12 was through NIOS / Open Schooling without a regular pre-qualification, you cannot be admitted to IPU Integrated Law &mdash; CUET score notwithstanding.
</p>

