<h2>Fee Structure 2026-27 (CUET-Admitted Law Students)</h2>

<ul>
<li><strong>USLLS (USS) BA-LLB / BBA-LLB:</strong> Tuition Rs. 1,45,200 per annum 2026-27 + university charges + exam fee &asymp; Rs. 1,80,000 Year 1 total (USS excluded from management quota).</li>
<li><strong>Affiliated Law colleges:</strong> Tuition typically Rs. 1,30,000-1,55,000 per year per the 6th SFRC Delhi Gazette Notification dated 14.07.2025, plus university charges, exam fee, alumni and welfare contributions.</li>
<li><strong>Management quota seats</strong> follow the same regulated tuition. Capitation fee in any form is illegal under the Delhi Professional Colleges Act, 2007.</li>
</ul>

