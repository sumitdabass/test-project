<h2>Management Quota Through CUET — Integrated Law</h2>

<p>
Per Chapter 12 of the brochure, every unaided affiliated Law college reserves <strong>10% of its total seats</strong> as Management Quota. A valid CUET (UG) score is one of the three accepted qualifiers:
</p>

<ul>
<li><strong>Eligibility:</strong> Class 12 with 50% aggregate (best 4 including English) <em>plus</em> a valid <strong>CLAT / IPU CET / CUET</strong> score (Instruction #21 + Chapter 12 Note 2).</li>
<li><strong>BCI bar still applies</strong> &mdash; Open School candidates without basic qualification cannot apply, even via management quota.</li>
<li><strong>Application:</strong> Apply directly to the college during the 18-day window advertised in 2 newspapers (Hindi + English).</li>
<li><strong>Registration fee cap:</strong> Rs. 2,500 per the Admission Regulatory Committee.</li>
<li><strong>Last date:</strong> 9 calendar days after the regular reporting date of the last GGSIPU counselling round.</li>
<li><strong>Aggregate calculation:</strong> Best 5 subjects including English and the mandatory subjects (per Chapter 12, "For UG Programme").</li>
</ul>

