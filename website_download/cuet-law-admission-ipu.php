<h2>How CUET Works for IPU Law (BA-LLB &amp; BBA-LLB) 2026-27</h2>

<p>
Per Section 1.1 ("At a Glance") of the GGSIPU UG Admission Brochure 2026-27, the 5-year Integrated Law admission at IP University (Programme Code <strong>121</strong> &mdash; covering Integrated BA-LLB Hons, BA-LLB, Integrated BBA-LLB Hons and BBA-LLB) is structured as a <strong>two-tier merit list</strong>:
</p>

<ol>
<li><strong>First preference:</strong> National Level Test &mdash; <strong>CLAT UG 2026</strong> (Common Law Admission Test conducted by the Consortium of National Law Universities).</li>
<li><strong>Second pathway:</strong> <strong>CUET (UG) 2026 #</strong> &mdash; used to fill vacant seats remaining after CLAT-based counselling rounds (Important Instruction #37).</li>
</ol>

<p>
A Law aspirant who only has a CUET score (and not CLAT) is still admissible &mdash; through the CUET vacant-seat round and through the management quota route at IPU's affiliated Law colleges.
</p>

<p style="font-size:13px;background:#fff8e6;padding:12px 16px;border-left:4px solid #f59e0b;border-radius:4px;color:#7c5410">
<strong>Important:</strong> The above applies only to the <strong>5-year Integrated Law programme (Code 121)</strong>. The <strong>3-year LLB programme (Code 238)</strong> is admitted only through GGSIPU CET 2026 &mdash; CUET does NOT apply for 3-year LLB per Chapter 2 of the brochure. See the dedicated <a href="/law-3-year-admission-ipu.php">Law (3-Year) admission page</a> for Programme Code 238 eligibility, fees and counselling.
</p>

