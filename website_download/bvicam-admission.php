<h2>BVICAM Admission Process 2026</h2>

<p>Admission to BA(JMC) at BVICAM is conducted through <strong>CUET (UG)</strong> merit followed by centralised GGSIPU online counselling. Candidates must register on ipu.ac.in after CUET results, lock BVICAM as a college preference and participate in the centralised counselling rounds.</p>

<p>Admission to MCA at BVICAM is through the <strong>GGSIPU CET (MCA)</strong> entrance test followed by centralised online counselling. Eligibility for MCA is a Bachelor's degree of minimum 3 years duration with Mathematics at 10+2 or graduation level, and minimum 50% aggregate (45% for SC/ST/OBC/PwD) per the 2026-27 brochure.</p>

<p>10% Management Quota seats are reserved at BVICAM per Section 12(1)(a) of the Delhi Professional Colleges Act, 2007 (Chapter 12 of the GGSIPU Brochure 2026-27). Management quota candidates must still qualify the corresponding entrance test (CUET / IPU CET) per Important Instruction #21 + Chapter 12 Note 2; registration fee is capped at Rs. 2,500.</p>

