<p>Bharati Vidyapeeth's Institute of Computer Applications and Management (BVICAM) is one of two IPU-affiliated institutes of the Bharati Vidyapeeth Education Society in Paschim Vihar, the other being <a href="BVP.php">Bharati Vidyapeeth's College of Engineering (BVP)</a>. While BVP focuses on B.Tech engineering programmes, <strong>BVICAM is the dedicated centre for journalism &amp; mass communication and computer applications</strong> &mdash; offering BA(JMC) at the undergraduate level and MCA at the postgraduate level under GGSIPU.</p>

