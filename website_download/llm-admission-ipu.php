  <h2>LL.M. Specialisations at USLLS — Career Paths</h2>
  <p>The LL.M. programme at USLLS offers the four specialisations notified in Chapter 2 of the PG Brochure 2026-27. Career emphasis by specialisation:</p>
  <ul>
    <li><strong>LL.M. (Corporate Law):</strong> Company law, securities regulation, mergers &amp; acquisitions, banking law. Best fit for in-house corporate counsel and corporate transaction practice.</li>
    <li><strong>LL.M. (Intellectual Property Right):</strong> Patents, trademarks, copyright, trade secrets, technology transfer. Strong fit for IP litigation, patent prosecution and tech-sector legal advisory.</li>
    <li><strong>LL.M. (Criminal Justice System):</strong> Criminal jurisprudence, evidence law, forensic law, criminal procedure reform. Suits criminal law practitioners, prosecutors and judicial aspirants.</li>
    <li><strong>LL.M. (Alternate Dispute Resolution):</strong> Arbitration, mediation, conciliation, online dispute resolution. Aligned with the institutional ADR push under the Mediation Act 2023 and Arbitration &amp; Conciliation Act amendments.</li>
  </ul>
  <p>For LL.M. aspirants who intend to enrol as advocates, note that this specialisation choice (made during counselling) is reflected on the final degree certificate.</p>

  <h2>LLM Curriculum &ndash; What You Will Study</h2>
  <p>The 1-year LLM programme at IPU is divided into 2 semesters:</p>
  <ul>
    <li><strong>Semester 1:</strong> Core subjects common to all specialisations including Research Methodology, Legal Theory &amp; Jurisprudence, and specialisation-specific papers.</li>
    <li><strong>Semester 2:</strong> Advanced specialisation papers, electives, and a dissertation on an approved research topic under faculty supervision.</li>
    <li><strong>Dissertation:</strong> A mandatory research dissertation that demonstrates original legal analysis and academic rigour.</li>
  </ul>

  <h2>Career Scope After LLM from IPU</h2>
  <p>An LLM from IPU opens up several career paths:</p>
  <ul>
    <li><strong>Legal practice:</strong> Specialise as a corporate lawyer (Corporate Law track), IP attorney (IPR track), criminal-justice practitioner (Criminal Justice System track), or ADR neutral / arbitrator (ADR track) — the four USLLS LL.M. specialisations per PG Brochure 2026-27 Ch 13.</li>
    <li><strong>Judiciary:</strong> LLM is highly valued in judicial services examinations and adds weightage to your candidature for judge positions.</li>
    <li><strong>Academia:</strong> Teach law at universities and law colleges &mdash; UGC NET combined with LLM qualifies you for assistant professor positions.</li>
    <li><strong>Corporate sector:</strong> Work as in-house counsel, legal advisor, or compliance officer at major corporations.</li>
    <li><strong>Government &amp; policy:</strong> Roles in legal departments, law commissions, regulatory bodies, and think tanks.</li>
    <li><strong>PhD in Law:</strong> Continue research by pursuing a doctoral programme at top universities.</li>
  </ul>

