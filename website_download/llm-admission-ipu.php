    <li><strong>Entrance exam:</strong> Valid <strong>CLAT-PG 2026</strong> score is mandatory. GGSIPU does not conduct its own CET for LL.M. admission.</li>
    <li><strong>Foreign Law Degree:</strong> An equivalent Law Degree from a Foreign University is also accepted, subject to the same 55% threshold.</li>
