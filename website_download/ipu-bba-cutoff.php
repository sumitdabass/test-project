<!-- How to read these cutoffs -->
<h2 style="font-size:22px;color:#0d1b6e;margin:36px 0 12px">How to Read These Cutoffs</h2>
<ul style="line-height:1.8;color:#334155;font-size:15px">
<li><strong>Min Rank</strong> is the topper who joined that college. <strong>Max Rank</strong> is the closing rank — the last candidate who got a seat in that round.</li>
<li><strong>Delhi Region</strong> = 85% reservation for candidates with Class 12 from a Delhi school. <strong>Outside Delhi</strong> = 15% reservation for the rest of India.</li>
<li><strong>Shift I</strong> and <strong>Shift II</strong> are separate seat allocations at colleges running two batches (typical for BPIT, BCIPS, CPJ CHS, etc.). Each shift has its own cutoff.</li>
<li>Cutoffs are <strong>CUET (UG) 2025 ranks</strong> — not CUET marks. Lower rank = better performance.</li>
<li>If your rank exceeds the Round 3 closing rank for a college, the public counselling door is closed — but <strong>management quota seats</strong> at unaided private colleges remain available (Important Instruction #21, GGSIPU 2026-27 brochure).</li>
</ul>

