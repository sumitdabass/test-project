<h2>Fee Structure 2026-27 (CUET-Admitted BBA Students)</h2>

<ul>
<li><strong>USMS (USS) BBA-MBA Integrated:</strong> Tuition Rs. 1,21,000 per annum 2026-27 + university charges + exam fee &asymp; Rs. 1,55,000-1,60,000 Year 1 total (USS is not open to management quota).</li>
<li><strong>Affiliated BBA colleges:</strong> Tuition typically Rs. 1,15,000-1,40,000 per year per the 6th SFRC Delhi Gazette Notification dated 14.07.2025, plus university charges, exam fee, alumni and welfare contributions.</li>
<li><strong>Management quota seats</strong> follow the same regulated tuition. Be cautious of any agent quoting "lakhs in cash" — capitation fee is illegal under the Delhi Professional Colleges Act, 2007.</li>
</ul>

