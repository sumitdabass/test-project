<h2>Fee Structure 2026-27 (CUET-Admitted B.Tech Students)</h2>

<p>The fee structure does not change based on entrance route &mdash; CUET-admitted and JEE-Main-admitted students pay the same. Per Chapter 14 (Part E):</p>

<ul>
<li><strong>USS (USIC&amp;T / USAR / USCT):</strong> Tuition Rs. 1,69,400 + university charges Rs. 20,000 + exam Rs. 3,000 + innovation Rs. 500 + infrastructure Rs. 10,000 + alumni one-time Rs. 2,000 = <strong>Rs. 2,04,900 (Year 1 total)</strong></li>
<li><strong>Affiliated colleges (MAIT/MSIT/BPIT/GTBIT/BVP etc.):</strong> Tuition <strong>Rs. 1,41,750 to Rs. 1,55,700 per year</strong> per the 6th SFRC Delhi Gazette Notification dated 14.07.2025, plus university charges, exam, innovation, alumni and welfare contributions (~Rs. 25,000-30,000 additional)</li>
<li><strong>Management quota seats</strong> at the same colleges typically charge the same regulated tuition fee (the 6th SFRC capped fee applies to all seats including management quota). Watch out for over-quotation by college agents.</li>
</ul>

