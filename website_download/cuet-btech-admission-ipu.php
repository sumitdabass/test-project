<h2>Management Quota Through CUET — B.Tech</h2>

<p>
Per Chapter 12 (Management Quota Admissions) of the brochure, every unaided affiliated B.Tech college reserves <strong>10% of its total seats</strong> as Management Quota seats. A valid CUET (UG) score is one of the three accepted qualifiers:
</p>

<ul>
<li><strong>Eligibility (Important Instruction #21 + Chapter 12 Note 2):</strong> The candidate must have qualified <em>JEE Main / GGSIPU CET 2026 / <strong>CUET</strong></em>, plus meet the Class 12 PCM 55% rule.</li>
<li><strong>Application:</strong> Each college runs its own management-quota counselling. Apply directly to the college during the 18-day window advertised in 2 newspapers (1 Hindi + 1 English).</li>
<li><strong>Registration fee cap:</strong> Rs. 2,500 (Admission Regulatory Committee).</li>
<li><strong>Timing:</strong> Last date is 9 calendar days after the regular reporting date of the last GGSIPU online round.</li>
<li><strong>Admission is provisional</strong> until ratified by GGSIPU as the designated agency.</li>
</ul>

