<h2>How CUET Works for IPU B.Tech 2026-27</h2>

<p>
Per the GGSIPU UG Admission Brochure 2026-27 (Section 1.1, "At a Glance"), B.Tech admission at IP University is structured as a <strong>two-tier merit list</strong>:
</p>

<ol>
<li><strong>First preference:</strong> National Level Test &mdash; <strong>JEE Main Paper-I</strong>. The University does not conduct a separate engineering CET; it directly uses JEE Main 2026 NTA merit.</li>
<li><strong>Second pathway:</strong> <strong>CUET (UG) 2026 #</strong> &mdash; used to fill vacant seats remaining after JEE Main counselling rounds (Important Instruction #37).</li>
</ol>

<p>
This means a B.Tech aspirant who only has a CUET score (and not JEE Main) is still eligible for IPU admission &mdash; through the CUET vacant-seat round and through the management quota route at affiliated colleges.
</p>

<hr>

<h2>Eligibility for B.Tech via CUET (Programme Code 131)</h2>

<p>Per Chapter 2 (Eligibility Criteria &amp; Admission Criteria) of the brochure:</p>

<ul>
<li>Pass in <strong>Class 12 (10+2)</strong> of CBSE or equivalent with a minimum aggregate of <strong>55% in Physics, Chemistry &amp; Mathematics</strong> (PCM), provided the candidate has passed in each subject separately.</li>
<li>The candidate must additionally have passed <strong>English</strong> as a subject of study (core / elective / functional) in the qualifying examination.</li>
<li>Marks are <strong>not rounded off</strong> &mdash; 54.99% will not be treated as 55% (Important Instruction #28).</li>
<li>For reserved categories (SC/ST/OBC/PwD), the minimum is relaxed to 50%.</li>
<li><strong>Blind (including colour blind), deaf or dumb candidates are not eligible</strong> for B.Tech (per Chapter 2 footnote).</li>
</ul>

<p>
For B.Tech Biotechnology (Code 130) the same 55% applies but in PCB / PC-Biotech as an alternative; CUET is also the secondary path (Section 1.1 row 16).
</p>

<hr>

<h2>CUET (UG) Subject Papers Required for IPU B.Tech</h2>

<p>Per Chapter 2, Programme Code 131 (Domain Specific Subjects column), candidates appearing in CUET (UG) for IPU B.Tech should attempt:</p>

<ul>
<li><strong>Section II &mdash; Physics (Code 322)</strong></li>
<li><strong>Section II &mdash; Chemistry (Code 306)</strong> <em>or</em> <strong>Computer Science / Informatics Practices (Code 308)</strong> (for CSE/IT/AI/DS major disciplines)</li>
<li><strong>Section II &mdash; Mathematics / Applied Mathematics (Code 319)</strong></li>
</ul>

<p>
Section IA English (Code 101) is recommended as the language paper since English is a compulsory eligibility subject.
</p>

<p style="font-size:13px;color:#666"><em>Per Section 1.2 of the brochure: <em>"during the Academic Session 2026-27, the methodology for conduct of CUET may be as per the notification to be issued by the University in due course of time"</em>. Final paper-mapping will be confirmed by GGSIPU on ipu.ac.in before counselling.</em></p>

