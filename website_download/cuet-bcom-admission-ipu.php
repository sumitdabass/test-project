<h2>CUET (UG) Subject Papers Required for IPU B.Com (Hons)</h2>

<p>Per Chapter 2, Programme Code 146 (Domain Specific Subjects column), candidates appearing in CUET (UG) for IPU B.Com Honours should attempt <strong>at least one</strong> of the following:</p>

<ul>
<li><strong>Section IA &mdash; English (Code 101)</strong></li>
<li><strong>Section II &mdash; Accountancy / Book Keeping (Code 301)</strong></li>
<li><strong>Section III &mdash; General Aptitude Test (Code 501)</strong></li>
</ul>

<p>
The strongest combination is all three (English + Accountancy + General Aptitude). Commerce-stream students should definitely attempt Accountancy. Non-Commerce stream students who cleared 5 subjects in Class 12 (one language + 4 electives) can rely on English + General Aptitude Test.
</p>

