<h2>Management Quota Through CUET — B.Com (Hons)</h2>

<p>
Per Chapter 12 of the brochure, every unaided affiliated B.Com college reserves <strong>10% of its total seats</strong> as Management Quota. A valid CUET (UG) score is one of the three accepted qualifiers:
</p>

<ul>
<li><strong>Eligibility:</strong> Class 12 with 50% aggregate (pass in 5 subjects) <em>plus</em> a valid <strong>IPU CET / JEE Main / CUET</strong> score (Instruction #21 + Chapter 12 Note 2).</li>
<li><strong>Application:</strong> Apply directly to the college during the 18-day window advertised in 2 newspapers (Hindi + English).</li>
<li><strong>Registration fee cap:</strong> Rs. 2,500 per the Admission Regulatory Committee.</li>
<li><strong>Last date:</strong> 9 calendar days after the regular reporting date of the last GGSIPU counselling round.</li>
<li><strong>Aggregate calculation:</strong> "For most of the UG Programme calculating aggregate marks obtained in the qualifying examination aggregate marks of <strong>best 5 subjects</strong> should be taken which includes English and the mandatory subjects" (Chapter 12).</li>
</ul>

<hr>

<h2>Fee Structure 2026-27 (CUET-Admitted B.Com Students)</h2>

<ul>
<li><strong>USMS (USS) B.Com Hons:</strong> Tuition Rs. 1,21,000 per annum 2026-27 + university charges + exam fee &asymp; Rs. 1,55,000-1,60,000 Year 1 total (USS excluded from management quota).</li>
<li><strong>Affiliated B.Com colleges:</strong> Tuition typically Rs. 1,15,000-1,40,000 per year per the 6th SFRC Delhi Gazette Notification dated 14.07.2025, plus university charges, exam fee, alumni and welfare contributions.</li>
<li><strong>Management quota seats</strong> follow the same regulated tuition. Capitation fee in any form is illegal under the Delhi Professional Colleges Act, 2007.</li>
</ul>

