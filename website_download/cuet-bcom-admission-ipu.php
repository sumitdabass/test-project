<h2>Eligibility for B.Com (Hons) via CUET (Programme Code 146)</h2>

<p>Per Chapter 2 of the brochure:</p>

<ul>
<li><strong>50% in aggregate in 10+2 / Senior School Certificate Examination of CBSE</strong> as minimum marks for admission to B.Com, with pass in <strong>five subjects (one language and four elective subjects)</strong>; or an examination recognized as equivalent to that.</li>
<li>Other accepted qualifications (per Chapter 2):
<ul>
<li>Pre-University Examination (Two years after ten years of schooling) of an Indian school / college.</li>
<li>Intermediate Examination of an Indian University / Board (Pass in five written subjects).</li>
<li>Indian School Certificate Examination (12 years) conducted by the Council for the Indian School Certificate Examination, New Delhi (Pass in five written subjects).</li>
<li>Examination of a foreign University / Board recognized as equivalent to 10+2 CBSE / Indian University.</li>
</ul></li>
<li>Reserved categories (SC/ST/OBC/PwD) get the standard 5% relaxation per university policy.</li>
<li>Marks are <strong>not rounded off</strong> &mdash; 49.99% will not become 50% (Important Instruction #28).</li>
</ul>

