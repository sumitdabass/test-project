<h2>DSPSR Admission Process 2026</h2>

<p>Admission to all programmes at DSPSR is conducted through the centralised GGSIPU online counselling process. The entrance exam for BBA, B.Com (Hons.) and BCA is <strong>CUET (UG)</strong>. Candidates must register on the GGSIPU admission portal after CUET results, lock DSPSR as a college preference and participate in the centralised online counselling rounds. 10% Management Quota seats are reserved per Section 12(1)(a) of the Delhi Professional Colleges Act, 2007 (Chapter 12 of the GGSIPU Brochure 2026-27); management quota candidates must still qualify CUET per Important Instruction #21 + Chapter 12 Note 2; registration fee is capped at Rs. 2,500.</p>

