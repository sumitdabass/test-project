<h2>Eligibility for Law (3-Year) Admission at IPU (Programme Code 238)</h2>

<p>Per Chapter 2 of the brochure (page 63):</p>

<ul>
<li>The candidate <strong>must have passed graduation in any discipline</strong> with <strong>50% marks</strong> from a recognized University or Institutions recognized by University / UGC / Governments.</li>
<li>Reserved categories (SC/ST/OBC/PwD): relaxation in percentage of marks as per the provisions of the Undergraduate Admission Brochure 2026-27.</li>
<li>Course Duration: <strong>3 Years</strong>.</li>
<li>Marks are <strong>not rounded off</strong> for the eligibility threshold.</li>
</ul>

<p style="font-size:13px;background:#fee2e2;padding:12px 16px;border-left:4px solid #dc2626;border-radius:4px;color:#7f1d1d">
<strong>BCI Bar (Critical):</strong> Per Chapter 2 of the brochure quoting BCI Letter <strong>BCI:D:1823/2010 (LE) dated 31.11.2010</strong>: <em>"The applicants who have obtained 10+2 or graduation/post graduation through Open Universities system directly without having any basic qualification for prosecuting such students are not eligible for admission in the law courses."</em> If your graduation was through an Open University without a regular pre-qualification (regular Class 12), you cannot be admitted to Law (3-Year) at IPU — CET score notwithstanding.
</p>

<hr>

<h2>GGSIPU CET 2026 Test Pattern for Programme Code 238</h2>

<p>Per the "Subjects of Entrance Test (CET)" column in Chapter 2 of the brochure for Programme Code 238, the GGSIPU CET 2026 paper for the 3-year LLB has three sections:</p>

<ul>
<li><strong>Language &amp; Comprehension &mdash; 25%</strong></li>
<li><strong>General Knowledge &amp; Current Affairs &mdash; 25%</strong></li>
<li><strong>Basic Understanding of Law and Legal Reasoning &mdash; 50%</strong></li>
</ul>

<p>
The Law &amp; Legal Reasoning section carries the highest weight. The paper is set both in English and Hindi (except sections that are inherently English-medium). The Common Merit Rank (CML) drawn from this CET is the sole basis of admission.
</p>

