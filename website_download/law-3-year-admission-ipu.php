<ol>
<li><strong>Confirm graduation eligibility</strong> &mdash; minimum 50% in any discipline from a recognized University. If your Class 12 or graduation was through Open Schooling without a regular pre-qualification, the BCI bar applies.</li>
<li><strong>Register for GGSIPU CET 2026</strong> at <a href="https://ipu.admissions.nic.in" target="_blank" rel="noopener">ipu.admissions.nic.in</a> &mdash; select Programme Code <strong>238</strong> (LLB Three Years Programme).</li>
<li>Appear in the GGSIPU CET 2026 on the scheduled date. Test pattern: Language &amp; Comprehension 25% + GK &amp; Current Affairs 25% + Law &amp; Legal Reasoning 50%.</li>
<li>Wait for the result and the GGSIPU Common Merit Rank (CML).</li>
<li><strong>Register for centralized online counselling</strong> on ipu.admissions.nic.in, fill college choices in order of preference, lock preferences.</li>
<li>If allotted, pay the Part Academic Fee, complete online document verification, report to the allotted college.</li>
<li><strong>Parallel track &mdash; Management Quota:</strong> Apply directly during each affiliated college's advertised 18-day management-quota window with graduation marksheet, CET scorecard, ID and photo. Note: USLLS is NOT in management quota.</li>
