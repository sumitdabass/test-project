<h2>Management Quota Through CET — Law (3-Year)</h2>

<p>
Per Chapter 12 of the brochure, every unaided affiliated Law college reserves <strong>10% of its total seats</strong> as Management Quota. For Programme Code 238 candidates, a valid <strong>GGSIPU CET</strong> score is the qualifier:
</p>

<ul>
<li><strong>Eligibility:</strong> Graduation in any discipline with 50% aggregate <em>plus</em> a valid GGSIPU CET 2026 (Programme Code 238) score (Important Instruction #21 + Chapter 12).</li>
<li><strong>BCI bar still applies</strong> &mdash; Open School candidates without basic qualification cannot apply, even via management quota.</li>
<li><strong>Application:</strong> Apply directly to the affiliated college during the 18-day window advertised in 2 newspapers (Hindi + English).</li>
<li><strong>Registration fee cap:</strong> Rs. 2,500 per the Admission Regulatory Committee.</li>
<li><strong>Last date:</strong> 9 calendar days after the regular reporting date of the last GGSIPU counselling round.</li>
<li><strong>USLLS (USS) is NOT open to management quota</strong> &mdash; only affiliated colleges.</li>
</ul>

