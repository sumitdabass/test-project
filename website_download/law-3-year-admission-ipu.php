        <li>One-time payments: Alumni Contribution Fund Rs. 2,000.</li>
        <li><strong>Total Year 1: Rs. 1,80,700</strong>. Year 2: Rs. 1,93,220. Year 3: Rs. 2,09,192.</li>
    </ul>
</li>
<li><strong>Affiliated Law colleges in Delhi:</strong> Tuition fee per <strong>F.No. DHE.18(1)/6th SFRC/2023/3205-15 dated 14th July 2025</strong> (6th SFRC notification, Appendix 13(i) of the brochure). Plus University Charges Rs. 20,000/year, Security Deposit Rs. 10,000 (one-time refundable), Alumni Fund Rs. 2,000 one-time, Examination Fee Rs. 3,000/year, Innovation &amp; Incubation Fee Rs. 500/year, Student Welfare Activity Fee Rs. 1,000/year (non-refundable).</li>
<li><strong>Capitation fee in any form is illegal</strong> under the Delhi Professional Colleges Act, 2007 (Section 6).</li>
</ul>

