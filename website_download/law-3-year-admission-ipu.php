<h2>How Admission Works for Law (3-Year) at IPU 2026-27</h2>

<p>
Per Section 1.1 ("At a Glance — Details of Graduation Programmes offered and applicable Entrance Test") of the GGSIPU UG Admission Brochure 2026-27, the Law (3-Year) Programme — listed at Sr. No. 35, <strong>Programme Code 238</strong> — has a <strong>single admission pathway</strong>:
</p>

<ul>
<li><strong>GGSIPU CET 2026</strong> — the Common Entrance Test conducted by Guru Gobind Singh Indraprastha University. This is the <strong>only</strong> route. Per Chapter 2 of the brochure: <em>"Admissions in this programme will be held on the basis of Common Merit Rank (CML) obtained in the Common Entrance Test (CET) to be conducted by the University."</em></li>
</ul>

<p style="font-size:13px;background:#fff8e6;padding:12px 16px;border-left:4px solid #f59e0b;border-radius:4px;color:#7c5410">
<strong>Important:</strong> CUET is <strong>NOT</strong> accepted for Programme Code 238. The "Domain Specific Subjects under CUET 2026" column in Chapter 2 is blank for this programme. There is also no National Level Test pathway. Candidates who have only a CUET or CLAT score (and not the GGSIPU CET) are not admissible to the 3-year LLB at IPU.
</p>

