  <h1>MCA Admission IPU 2026 &ndash; Programme Code 105 Complete Guide</h1>

  <p>The Master of Computer Applications (MCA) at Guru Gobind Singh Indraprastha University (GGSIPU) is one of the most sought-after postgraduate IT programmes in Delhi NCR. Offered under <strong>Programme Code 105</strong>, this 2-year course prepares graduates for careers in software development, data engineering, cloud, cybersecurity and IT consulting. MCA at IPU is delivered both at the flagship University School of Information &amp; Communication Technology (USICT) and at 12+ affiliated colleges spread across Delhi NCR.</p>

  <p>Want to secure an MCA seat at IPU in 2026? Call <a href="tel:+919899991342"><strong>9899991342</strong></a> for free expert guidance on NIMCET preparation, college selection and the IPU counselling process.</p>

  <h2>About MCA at IPU</h2>
  <p>The MCA programme at IPU is a 2-year (4 semester) full-time master's degree designed to develop skilled IT professionals. The curriculum covers advanced programming, software engineering, DBMS, data structures &amp; algorithms, computer networks, machine learning and a final-semester industry project. With both government and self-financed options available under GGSIPU, students get strong academic exposure plus solid placement support across Delhi NCR's IT industry.</p>

  <h2>Eligibility Criteria (Programme Code 105 — MCA / MCA Software Engineering)</h2>

  <p>Per <strong>Chapter 2 of the PG Brochure 2026-27 (page 33)</strong>:</p>

  <blockquote style="border-left:4px solid #1a3a9c;padding:8px 16px;margin:16px 0;background:#f0f7ff;color:#0d1b6e;font-style:italic">"1. (i) Passed BCA/B.Sc. (Computer Science)/B.Sc.(Information Technology)/B.Voc.(Software Development) or equivalent OR (ii) Passed at least 03 years Bachelors Degree with Mathematics/Business Statistics/Operation Research or equivalent etc. at 10+2 level or graduation level. 2. The applicant must have obtained at least 50% marks (45% marks in case of candidates belonging to reserved category) in the qualifying examination."</blockquote>

  <ul>
    <li>Path A: <strong>BCA / B.Sc (Computer Science) / B.Sc (Information Technology) / B.Voc (Software Development)</strong> or equivalent.</li>
    <li>Path B: At least <strong>3-year Bachelor's degree</strong> with Mathematics / Business Statistics / Operation Research or equivalent at 10+2 level or graduation level.</li>
    <li>Minimum marks: <strong>50% in the qualifying examination</strong> (45% for reserved categories per Chapter 6).</li>
    <li>Final-year students may apply provisionally subject to clearing the qualifying degree before admission.</li>
    <li>Equivalence (where required) is determined by a committee constituted by the Dean, USICT.</li>
  </ul>

  <h2>Entrance Tests for MCA Admission IPU 2026 (per PG Brochure Section 1.1)</h2>

  <p>Per Section 1.1 of the GGSIPU PG Admission Brochure 2026-27, MCA / MCA(SE) (Programme Code 105) admission follows a 3-tier merit list:</p>

  <ol>
    <li><strong>NIMCET 2026</strong> &mdash; National Level Test (NIT MCA Common Entrance Test). <em>Highest priority.</em></li>
    <li><strong>GGSIPU CET 2026</strong> &mdash; the University's own Common Entrance Test. Used to fill seats remaining vacant after NIMCET counselling. CET subjects: Mathematics (25%), English Language &amp; Comprehension (25%), Computer Awareness (25%), Logical &amp; Analytical Ability (25%).</li>
    <li><strong>CUET PG 2026 #</strong> &mdash; CUET PG paper SCQP09 fills any seats still vacant after CET counselling.</li>
  </ol>

  <p style="font-size:13px;color:#666"><em>Bridge courses: per Chapter 2 note, MCA/MCA(SE) admits may be required to study additional bridge courses as per University norms.</em></p>

  <h2>MCA Specialisations / Variations Offered</h2>
