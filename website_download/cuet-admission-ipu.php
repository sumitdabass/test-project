<h2>How to Register for CUET (UG) 2026</h2>

<ol>
<li>Visit the official CUET portal at the National Testing Agency (NTA) website &mdash; <strong>cuet.nta.nic.in</strong>.</li>
<li>Create your candidate account using a valid email and mobile number.</li>
<li>Fill the application form &mdash; you will choose your Section IA language paper (English etc.), Section II domain subjects (up to 6 papers based on Class 12 subjects) and Section III General Aptitude Test (optional but useful for BBA / B.Com / Law / Liberal Arts).</li>
<li>Pick the right domain papers for your target IPU course &mdash; see the per-course guides above.</li>
<li>Pay the application fee, upload documents, and submit. Download the confirmation page.</li>
<li>Appear in CUET (UG) 2026 on the scheduled date. NTA declares the result on its website.</li>
<li>Once GGSIPU notifies CUET-based counselling, register separately on <strong>ipu.admissions.nic.in</strong> with your CUET roll number and score.</li>
</ol>

<p style="font-size:13px;color:#666"><em>Per the brochure footnote: "The Candidates may visit the concerned official website for registration for CUET 2026." Registration for CUET is independent of GGSIPU CET 2026 &mdash; you can register for both.</em></p>

