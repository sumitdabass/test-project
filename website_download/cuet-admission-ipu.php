<h2>Management Quota Through CUET — Quick Facts</h2>

<ul>
<li><strong>10% of total seats</strong> at every unaided affiliated IPU college are reserved as Management Quota seats (Section 12(1)(a) of the Delhi Professional Colleges Act, 2007).</li>
<li>Excluded from management quota: <strong>University Schools of Studies (USS), Minority Status institutions, Government institutions, ACMS, AIE, AIMT</strong>.</li>
<li>To apply, the candidate <strong>must</strong> have a valid CUET / NLT / IPU CET 2026 score (Important Instruction #21 + Chapter 12, Note 2).</li>
<li>Each college runs its own management-quota counselling, advertised in 2 newspapers (1 Hindi + 1 English) at least 14 days before closing.</li>
<li>Application window: minimum 18 days. Registration fee capped at <strong>Rs. 2,500</strong> by the Admission Regulatory Committee.</li>
<li>Last date to fill management seats: <strong>9 calendar days after</strong> the last regular reporting date in the University.</li>
<li>All management-quota admissions are <strong>provisional</strong> until ratified by GGSIPU.</li>
</ul>

