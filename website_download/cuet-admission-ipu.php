<h2>What is CUET-Based Admission at IPU?</h2>

<p>
Guru Gobind Singh Indraprastha University accepts the <strong>Common University Entrance Test (CUET UG)</strong> conducted by the National Testing Agency as a valid score for admission to a wide range of undergraduate programmes — including B.Tech, BBA, B.Com (Honours), Integrated Law (BA-LLB / BBA-LLB), BCA, BJMC, BMS, BHMCT, B.Pharm, B.Ed and the 4-year UG programmes in English / Economics / Liberal Arts.
</p>

<p>
This page explains <em>exactly</em> how CUET fits into the IPU admission process per the official <strong>GGSIPU UG Admission Brochure 2026-27</strong>, and links to course-specific CUET guides for B.Tech, BBA, B.Com and Law.
</p>

<hr>

<h2>How CUET Works at IPU — The Two Pathways</h2>

<p>The brochure makes CUET useful in <strong>two distinct ways</strong>:</p>

<h3>Pathway 1 — Vacant Seat Filling (Important Instruction #37)</h3>

<p>
Per <em>Important Instruction #37</em> of the 2026-27 brochure: <em>"Filling up vacant seats on the basis of merit of CUET after exhausting the merit list of National Level Test / Common Entrance Test conducted by University. Any candidate who had secured any seat in any programme/college through NLT/CET of the University and has &lsquo;ADMITTED&rsquo; status shall not be granted any seat in any programme through the merit of CUET."</em>
</p>

<p>
In plain language: GGSIPU first runs counselling on the primary entrance (JEE Main for B.Tech, CLAT for Law, IPU CET for BBA / B.Com / BCA / BJMC / BMS etc.). Whatever seats remain unfilled are then offered to CUET-qualified candidates through additional counselling rounds. This gives students with strong CUET scores a real second chance even if they did not appear for IPU's own CET.
</p>

<h3>Pathway 2 — Management Quota Qualifier (Important Instruction #21 + Chapter 12)</h3>

<p>
Per <em>Important Instruction #21</em>: <em>"It is mandatory for all the candidates desirous of seeking admission through management quota that the said candidate should have either qualified in the notified National Level Test / GGSIPU CET 2026 / <strong>CUET</strong> or any other applicable entrance test for admission in various Programmes."</em>
</p>

<p>
This is reinforced in <em>Chapter 12, Note 2</em> of the Management Quota chapter. Every unaided affiliated IPU college (MAIT, MSIT, BPIT, GTBIT, VIPS-TC, ADGITM, BVP, MAIMS, JIMS Greater Noida, Echelon Faridabad and most others) reserves <strong>10% of its total seats as Management Quota</strong> per Section 12(1)(a) of the Delhi Professional Colleges Act, 2007. A valid CUET score qualifies you to apply for these management seats — alongside JEE Main / CLAT / IPU CET qualifiers.
</p>

