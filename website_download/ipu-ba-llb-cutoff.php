<h2 style="font-size:22px;color:#0d1b6e;margin:36px 0 12px">How to Read These Cutoffs</h2>
<ul style="line-height:1.8;color:#334155;font-size:15px">
<li><strong>Min Rank</strong> is the topper who joined that college. <strong>Max Rank</strong> is the closing rank — the last candidate who got a seat in that round.</li>
<li><strong>Delhi Region</strong> = 85% reservation for candidates with Class 12 from a Delhi school. <strong>Outside Delhi</strong> = 15% reservation for the rest of India.</li>
<li>Cutoffs are <strong>CLAT (UG) 2025 ranks</strong> — the entrance exam GGSIPU uses for integrated 5-year Law admissions. Lower rank = better performance.</li>
